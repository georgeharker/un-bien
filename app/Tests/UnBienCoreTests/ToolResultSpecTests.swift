import XCTest
@testable import UnBienCore

/// Stage 0 of the tool-result rendering plan (design 01M77YDWSZFD6WCYVFT3Z73SWJ):
/// fixtures transcribed from each tool's DECLARED result spec, in both forms the
/// app receives a tool call — the live rpc frames and the stored session
/// entries. These tests pin (1) that the fixtures are faithful to their specs,
/// (2) that the real session log follows the shared spec, and (3) how the
/// reducer treats live vs replay TODAY. The known divergence (replay drops
/// `details` and reshapes the result) is asserted under a strict expected
/// failure, so the stage-1 fix trips it and the expectation is flipped
/// deliberately.
final class ToolResultSpecTests: XCTestCase {
    // MARK: - Catalog

    private struct Fixture {
        let id: String
        let tool: String
        let toolCallID: String
        let args: JSONValue
        let live: [JSONValue]
        let stored: [JSONValue]
        let compat: String?
        let expect: JSONValue

        /// The settled live result object (tool_execution_end.result).
        var liveResult: JSONValue? {
            live.last(where: { $0["type"]?.stringValue == "tool_execution_end" })?["result"]
        }
        var liveIsError: Bool {
            live.last(where: { $0["type"]?.stringValue == "tool_execution_end" })?["isError"]?.boolValue ?? false
        }
        /// The stored toolResult message, when the record holds one.
        var storedResult: JSONValue? {
            stored.lazy.map { $0["message"] ?? .null }
                .first { $0["role"]?.stringValue == "toolResult" }
        }
    }

    /// app/Tests/Fixtures/tool-results/catalog.json (generated by generate.py
    /// next to it) and durable-catalog.json (captured from pi-durable's tools
    /// by unbien-durable/src/tool_fixtures.test.ts), two levels up.
    private func loadCatalog() throws -> [Fixture] {
        let dir = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .appendingPathComponent("Fixtures/tool-results")
        let fixtures = try ["catalog.json", "durable-catalog.json"].flatMap { name in
            try JSONDecoder().decode(JSONValue.self, from: Data(contentsOf: dir.appendingPathComponent(name)))["fixtures"]?
                .arrayValue ?? []
        }
        return fixtures.map { f in
            Fixture(id: f["id"]?.stringValue ?? "",
                    tool: f["tool"]?.stringValue ?? "",
                    toolCallID: f["toolCallId"]?.stringValue ?? "",
                    args: f["args"] ?? .object([:]),
                    live: f["live"]?.arrayValue ?? [],
                    stored: f["stored"]?.arrayValue ?? [],
                    compat: f["compat"]?.stringValue,
                    expect: f["expect"] ?? .object([:]))
        }
    }

    private func texts(_ content: JSONValue?) -> [String] {
        (content?.arrayValue ?? []).compactMap {
            $0["type"]?.stringValue == "text" ? $0["text"]?.stringValue : nil
        }
    }

    private func matches(_ s: String, _ pattern: String) -> Bool {
        s.range(of: pattern, options: .regularExpression) != nil
    }

    // MARK: - 1. Catalog integrity

    func testCatalogLoadsWithUniqueIDsAndBothForms() throws {
        let fixtures = try loadCatalog()
        XCTAssertGreaterThanOrEqual(fixtures.count, 30)
        XCTAssertEqual(Set(fixtures.map(\.id)).count, fixtures.count, "duplicate fixture id")
        for f in fixtures {
            XCTAssertFalse(f.live.isEmpty, "\(f.id): no live frames")
            XCTAssertFalse(f.stored.isEmpty, "\(f.id): no stored entries")
            XCTAssertNotNil(f.expect["face"]?.stringValue, "\(f.id): no expected face")
            XCTAssertNotNil(f.expect["category"]?.stringValue, "\(f.id): no expected category")
        }
    }

    /// pi's invariant: the stored toolResult message carries the SAME content,
    /// details and isError the live tool_execution_end did
    /// (pi-agent-core createToolResultMessage). Compat fixtures model producers
    /// that break it on purpose.
    func testLiveAndStoredCarryTheSameResult() throws {
        for f in try loadCatalog() where f.compat == nil {
            guard let live = f.liveResult, let stored = f.storedResult else {
                XCTFail("\(f.id): missing a form"); continue
            }
            XCTAssertEqual(live["content"], stored["content"], "\(f.id): content")
            XCTAssertEqual(live["details"], stored["details"], "\(f.id): details")
            XCTAssertEqual(f.liveIsError, stored["isError"]?.boolValue ?? false, "\(f.id): isError")
        }
    }

    // MARK: - 2. Fixtures follow their tool's spec

    func testFixturesFollowTheirToolSpecs() throws {
        let truncationKeys: Set<String> = ["content", "truncated", "truncatedBy", "totalLines",
            "totalBytes", "outputLines", "outputBytes", "lastLinePartial",
            "firstLineExceedsLimit", "maxLines", "maxBytes"]
        for f in try loadCatalog() {
            guard let result = f.storedResult ?? f.liveResult else { continue }
            // Shared: content is text and image blocks only.
            for block in result["content"]?.arrayValue ?? [] {
                XCTAssertTrue(["text", "image"].contains(block["type"]?.stringValue ?? ""),
                              "\(f.id): content block type")
            }
            let joined = texts(result["content"]).joined(separator: "\n")
            let details = result["details"]
            if let truncation = details?["truncation"]?.objectValue {
                // pi-durable's TruncationResult leaves out the truncated text.
                let expected = f.id.hasPrefix("durable.") ? truncationKeys.subtracting(["content"]) : truncationKeys
                XCTAssertEqual(Set(truncation.keys), expected, "\(f.id): TruncationResult fields")
            }
            switch f.id {
            case "bash.exit-code":
                XCTAssertTrue(matches(joined, #"\n\nCommand exited with code \d+$"#), f.id)
            case "bash.aborted":
                XCTAssertTrue(joined.hasSuffix("\n\nCommand aborted"), f.id)
                XCTAssertEqual(details, .object([:]), "\(f.id): createErrorToolResult details")
            case "bash.truncated":
                XCTAssertTrue(matches(joined, #"\n\n\[Showing lines \d+-\d+ of \d+\. Full output: \S+\]$"#), f.id)
                XCTAssertNotNil(details?["fullOutputPath"]?.stringValue, f.id)
            case "read.ranged":
                XCTAssertTrue(matches(joined, #"\n\n\[\d+ more lines in file\. Use offset=\d+ to continue\.\]$"#), f.id)
            case "read.truncated":
                XCTAssertTrue(matches(joined, #"\n\n\[Showing lines \d+-\d+ of \d+\. Use offset=\d+ to continue\.\]$"#), f.id)
            case "read.image":
                XCTAssertTrue(joined.hasPrefix("Read image file ["), f.id)
                XCTAssertEqual(result["content"]?.arrayValue?.filter { $0["type"]?.stringValue == "image" }.count, 1, f.id)
            case "edit.ok":
                XCTAssertTrue(matches(joined, #"^Successfully replaced \d+ block\(s\) in .+\.$"#), f.id)
                XCTAssertNotNil(details?["diff"]?.stringValue, f.id)
                XCTAssertNotNil(details?["firstChangedLine"], f.id)
                XCTAssertTrue(matches(details?["patch"]?.stringValue ?? "", #"(?m)^@@ -\d+(,\d+)? \+\d+(,\d+)? @@"#),
                              "\(f.id): patch is a unified diff")
            case "write.ok":
                XCTAssertTrue(joined.hasPrefix("Successfully wrote to "), f.id)
                XCTAssertNil(details, "\(f.id): write has no details")
            case "grep.limit":
                XCTAssertTrue(matches(joined, #"\n\n\[[^\]]+\]$"#), "\(f.id): notices block")
            case "codemode.completed", "codemode.failed":
                let first = texts(result["content"]).first ?? ""
                XCTAssertTrue(matches(first, #"^Script (completed|failed)\nWall time [\d.]+ seconds\nOutput:\n$"#),
                              "\(f.id): header block")
                for call in details?["calls"]?.arrayValue ?? [] {
                    for key in ["id", "name", "args", "status"] {
                        XCTAssertNotNil(call[key], "\(f.id): calls[].\(key)")
                    }
                }
            case "codemode.rejected":
                XCTAssertFalse(matches(texts(result["content"]).first ?? "", #"^Script (completed|failed)\n"#),
                               "\(f.id): rejected input has no header")
            case "tool.not-found":
                XCTAssertTrue(matches(joined, #"^Tool \S+ not found$"#), f.id)
                XCTAssertEqual(details, .object([:]), f.id)
            case "durable.diagnostics":
                XCTAssertTrue(matches(texts(result["content"]).last ?? "", #"^<harness>\n[\s\S]*\n</harness>$"#), f.id)
            default:
                break
            }
            if f.expect["isError"]?.boolValue == true {
                XCTAssertTrue(result["isError"]?.boolValue ?? f.liveIsError, "\(f.id): isError")
            }
        }
    }

    // MARK: - 3. The real log follows the shared spec

    /// Every stored toolResult in the reference log: content is text/image
    /// blocks and isError a bool. `details` is any JSON value (pi-agent-core
    /// types it `T = JsonValue`): pi's built-in tools store an object or
    /// nothing, while other tools may store anything (un-bien's agent_request
    /// stores the reply body, often a string). The fixtures assume exactly
    /// this, so a pi change that broke it would show here.
    func testRealLogToolResultsFollowTheSharedSpec() throws {
        let path = "/Users/geohar/.local/share/pi/2026-10-14T15-47-40-528Z_"
            + "01a13b19-0f6f-72ef-aa88-5c17e5962b87.jsonl"
        guard FileManager.default.fileExists(atPath: path) else {
            throw XCTSkip("real session log not present on this machine")
        }
        var results = 0
        for line in try String(contentsOfFile: path, encoding: .utf8).split(separator: "\n") {
            guard let entry = try? JSONDecoder().decode(JSONValue.self, from: Data(line.utf8)),
                  let message = entry["message"], message["role"]?.stringValue == "toolResult"
            else { continue }
            results += 1
            let blocks = message["content"]?.arrayValue
            XCTAssertNotNil(blocks, "toolResult content is an array")
            for block in blocks ?? [] {
                XCTAssertTrue(["text", "image"].contains(block["type"]?.stringValue ?? ""))
            }
            let builtIn: Set<String> = ["bash", "read", "edit", "write", "grep", "find", "ls", "codemode"]
            if builtIn.contains(message["toolName"]?.stringValue ?? ""),
               let details = message["details"], details != .null {
                XCTAssertNotNil(details.objectValue,
                                "\(message["toolName"]?.stringValue ?? "?"): built-in details are an object")
            }
            XCTAssertNotNil(message["isError"]?.boolValue, "isError is a bool")
        }
        XCTAssertGreaterThan(results, 1000, "the real log loaded")
    }

    // MARK: - 4. Live vs replay through the reducer, as it stands

    private func liveCard(_ f: Fixture) -> ToolCard? {
        var state = SessionState()
        for frame in f.live { state.applyRPC(frame) }
        return card(in: state, f.toolCallID)
    }

    private func replayCard(_ f: Fixture) -> ToolCard? {
        var state = SessionState()
        state.applyEntries(f.stored, leafId: f.stored.last?["id"]?.stringValue, authoritative: true)
        return card(in: state, f.toolCallID)
    }

    private func liveThenReplayCard(_ f: Fixture) -> ToolCard? {
        var state = SessionState()
        for frame in f.live { state.applyRPC(frame) }
        state.applyEntries(f.stored, leafId: f.stored.last?["id"]?.stringValue, authoritative: true)
        return card(in: state, f.toolCallID)
    }

    private func card(in state: SessionState, _ id: String) -> ToolCard? {
        for case .tool(let c) in state.items where c.toolCallID == id { return c }
        return nil
    }

    /// What already holds in both paths: one card per call, the same identity
    /// and args, the same error state, the same images.
    func testBothPathsBuildTheSameCardIdentity() throws {
        for f in try loadCatalog() where f.compat == nil {
            guard let live = liveCard(f), let replay = replayCard(f) else {
                XCTFail("\(f.id): a path built no card"); continue
            }
            XCTAssertEqual(live.tool, replay.tool, f.id)
            XCTAssertEqual(live.args, replay.args, f.id)
            XCTAssertEqual(live.state, replay.state, "\(f.id): state")
            XCTAssertEqual(live.state == .failed, f.liveIsError, "\(f.id): isError -> failed")
            XCTAssertEqual(live.images.count, replay.images.count, "\(f.id): images")
        }
    }

    /// Stage 1: live and replay hold ONE canonical result value, so the
    /// replayed card equals the live one and a live card's replay fold leaves
    /// it unchanged. Includes the compat producers whose record holds a
    /// toolResult: a string result (pre-1.5 durable) canonicalizes to the same
    /// value the stored message gives.
    func testReplayEqualsLiveAndTheFoldKeepsIt() throws {
        for f in try loadCatalog() where f.storedResult != nil {
            guard let live = liveCard(f), let replay = replayCard(f),
                  let folded = liveThenReplayCard(f) else {
                XCTFail("\(f.id): a path built no card"); continue
            }
            XCTAssertEqual(live.result, replay.result, "\(f.id): result")
            XCTAssertEqual(live.output, replay.output, "\(f.id): output")
            XCTAssertEqual(live.images, replay.images, "\(f.id): images")
            XCTAssertEqual(live.state, replay.state, "\(f.id): state")
            XCTAssertEqual(live.result, folded.result, "\(f.id): fold kept the live result")
            XCTAssertEqual(live.output, folded.output, "\(f.id): fold kept the live output")
            // The duration comes from the record (the forwarded live frame
            // carries none today), and survives the fold.
            let stored = f.storedResult?["durationMs"]?.intValue
            XCTAssertEqual(replay.durationMs, stored, "\(f.id): durationMs")
            XCTAssertEqual(folded.durationMs, stored, "\(f.id): fold durationMs")
        }
    }

    /// The canonical value is `{content, details?}`: details kept exactly as
    /// sent (absent, an object, a string, null), live-only fields dropped.
    func testCanonicalResultKeepsContentAndDetailsOnly() throws {
        for f in try loadCatalog() where f.storedResult != nil {
            guard let card = replayCard(f), let result = card.result?.objectValue else {
                XCTFail("\(f.id): no canonical result"); continue
            }
            XCTAssertTrue(Set(result.keys).isSubset(of: ["content", "details"]), "\(f.id): keys")
            XCTAssertEqual(result["content"], f.storedResult?["content"], "\(f.id): content")
            XCTAssertEqual(result["details"], f.storedResult?.objectValue?["details"], "\(f.id): details")
        }
        // A live object's extra fields don't survive.
        let extra: JSONValue = .object(["content": .array([]), "details": .string("d"),
                                        "structuredContent": .object([:]), "isError": .bool(true),
                                        "terminate": .bool(true)])
        XCTAssertEqual(SessionState.canonicalToolResult(extra),
                       .object(["content": .array([]), "details": .string("d")]))
    }

    /// A failed card's error text is its content's text (pi puts a thrown
    /// error's message, an exit status, or a script error there).
    func testFailedCardsCarryTheirErrorText() throws {
        for f in try loadCatalog() where f.expect["isError"]?.boolValue == true {
            guard let card = replayCard(f) else { XCTFail(f.id); continue }
            XCTAssertEqual(card.state, .failed, f.id)
            XCTAssertNotNil(card.errorText, "\(f.id): error text")
            if let expected = f.expect["text"]?.stringValue {
                XCTAssertTrue(card.errorText?.contains(expected) ?? false, "\(f.id): error text content")
            }
        }
        for f in try loadCatalog() where f.expect["isError"]?.boolValue != true && !f.liveIsError {
            XCTAssertNil(replayCard(f)?.errorText, "\(f.id): no error text on success")
        }
    }
}
